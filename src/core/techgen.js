// Generated efficiency nodes of the tech tree (docs/MISSIONS-V2.md §4.3). Pure: no rng, no I/O, no state.
//
// A tech file (data/tech/eN/tech.json) may carry `templates[]` next to its authored `nodes[]`:
//   { "id": "lc", "branch": "propulsion", "effect": "launchCost", "values": [-0.02, -0.02, -0.03],
//     "names": ["…", "…", "…"], "shorts": ["…", "…", "…"], "icon": "🔥",
//     "after": "e1_prop_turbopump", "alsoAfter": [], "years": [1952, 1974],
//     "cost": [40, 90], "science": [8, 20], "weeks": [12, 24], "desc": "{name}: {effect}." }
// Each template expands into `values.length` nodes `g<n>_<branch>_<id>_<i>` (i from 1), chained: `_1` requires
// `after` + `alsoAfter`, `_i` requires `_{i-1}`. Years, cost, science and weeks are interpolated linearly over the
// chain (years and weeks to integers, cost to multiples of 5, science to integers); histYear = fromYear = the
// interpolated year. `desc` fills {name}, {short} and {effect} (pt-BR effect text, same wording as
// research.describeEffects). Ids are stable as long as the template id and the index are: never reorder `values`,
// only append. The prefix `g<digit>_` is reserved for generated nodes (the validator refuses it in authored ones).

/** Generated ids look like g3_propulsion_lc_2. */
export const GEN_ID = /^g\d_/;

const round = (x, step = 1) => Math.round(x / step) * step;
const lerp = (pair, t, fallback) => {
  if (!Array.isArray(pair)) return typeof pair === 'number' ? pair : fallback;
  const [a, b = a] = pair;
  return a + (b - a) * t;
};

/** pt-BR effect texts, same wording as research.describeEffects (kept here so src/core never imports src/sim), but
 * percentages keep one decimal when they have one (−1,5% instead of −2%). */
export function effectTexts(labels = {}, effects = {}) {
  const out = [];
  for (const [k, raw] of Object.entries(effects || {})) {
    if (typeof raw !== 'number' || !Number.isFinite(raw)) continue;
    const L = labels[k] || { label: k, unit: 'num' };
    const fmt = (x, d = 0) => x.toFixed(d).replace('.', ',');
    const sign = raw >= 0 ? '+' : '−';
    const a = Math.abs(raw);
    const dec = (x) => (Number.isInteger(round(x * 1000) / 10) ? 0 : 1); // 1.5% keeps its decimal
    switch (L.unit) {
      case 'pp': out.push(`${sign}${fmt(a * 100, dec(a))} p.p. ${L.label}`); break;
      case 'pct': out.push(`${sign}${fmt(a * 100, dec(a))}% ${L.label}`); break;
      case 'pctAbs': out.push(`${fmt(a * 100)}% mais ${L.label}`); break;
      case 'pctNeg': out.push(`−${fmt(a * 100, dec(a))}% ${L.label}`); break;
      case 'int': out.push(`${sign}${Math.floor(a + 1e-9)} ${L.label}`); break;
      default: out.push(`${sign}${fmt(a, a % 1 ? 1 : 0)} ${L.label}`);
    }
  }
  return out;
}

/** Tier number of a tech file: file.era (1..7), else the techTier 't3', else opts.era. */
function tierOf(file, tpl, opts) {
  const pick = (v) => (Number.isInteger(v) ? v : typeof v === 'string' && /^[et]\d$/.test(v) ? Number(v.slice(1)) : null);
  return pick(tpl?.era) ?? pick(tpl?.techTier) ?? pick(file?.era) ?? pick(file?.techTier) ?? pick(opts?.era) ?? null;
}

/**
 * Nodes generated by one template (pure; deterministic in the template alone).
 * @param {object} tpl
 * @param {{era:number, labels?:object, file?:object}} ctx
 */
export function expandTemplate(tpl, { era, labels = {} } = {}) {
  if (!tpl || typeof tpl.id !== 'string' || !Array.isArray(tpl.values) || !tpl.values.length || !Number.isInteger(era)) return [];
  const k = tpl.values.length;
  const out = [];
  for (let i = 0; i < k; i++) {
    const t = k === 1 ? 0 : i / (k - 1);
    const id = `g${era}_${tpl.branch}_${tpl.id}_${i + 1}`;
    const year = round(lerp(tpl.years, t, null));
    const name = tpl.names?.[i] || `${tpl.id} ${i + 1}`;
    const short = tpl.shorts?.[i] || name.slice(0, 30);
    const effects = { [tpl.effect]: tpl.values[i] };
    const effect = effectTexts(labels, effects).join(', ');
    const desc = String(tpl.desc || '{name}: {effect}.')
      .replaceAll('{name}', name).replaceAll('{short}', short).replaceAll('{effect}', effect);
    const node = {
      id, branch: tpl.branch, era, techTier: `t${era}`,
      fromYear: year, histYear: year,
      name, short, icon: tpl.icon || '⚙️', description: desc.slice(0, 160),
      cost: Math.max(5, round(lerp(tpl.cost, t, 50), 5)),
      science: Math.max(0, round(lerp(tpl.science, t, 10))),
      weeks: Math.max(1, round(lerp(tpl.weeks, t, 12))),
      requires: i === 0 ? [tpl.after, ...(tpl.alsoAfter || [])].filter((r) => typeof r === 'string' && r) : [`g${era}_${tpl.branch}_${tpl.id}_${i}`],
      effects,
      generated: tpl.id,
    };
    if (!Number.isFinite(year)) { delete node.fromYear; delete node.histYear; }
    if (tpl.untilYear != null) node.untilYear = tpl.untilYear;
    out.push(node);
  }
  return out;
}

/** Every generated node of a tech file, in template order. */
export function expandTemplates(file, opts = {}) {
  const out = [];
  for (const tpl of Array.isArray(file?.templates) ? file.templates : []) {
    out.push(...expandTemplate(tpl, { era: tierOf(file, tpl, opts), labels: opts.labels }));
  }
  return out;
}

/** Authored nodes followed by the generated ones (MISSIONS-V2 §14 B1 API: techgen.expand(techJson) → nodes[]). */
export function expand(file, opts = {}) {
  return [...(Array.isArray(file?.nodes) ? file.nodes : []), ...expandTemplates(file, opts)];
}

/**
 * The tech file as it is merged into data.tech: `nodes` = authored + generated; `templates` and the file-level
 * `era`/`techTier` are dropped (they only drive the expansion and would collide between eras when merged).
 * Files without templates are returned unchanged (the Corrida Lunar's data/tech.json stays value for value).
 */
export function prepareTechFile(file, opts = {}) {
  if (!file || typeof file !== 'object' || !Array.isArray(file.templates)) return file;
  const { templates, era, techTier, ...rest } = file;
  return { ...rest, nodes: expand(file, opts) };
}
